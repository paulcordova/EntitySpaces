        static public OracleCommand BuildDynamicInsertCommand(esDataRequest request, esEntitySavePacket packet)
        {
            Dictionary<string, OracleParameter> types = Cache.GetParameters(request);

            OracleCommand cmd = new OracleCommand();
            cmd.BindByName = true;
            if (request.CommandTimeout != null) cmd.CommandTimeout = request.CommandTimeout.Value;

            string comma = String.Empty;
            string into = String.Empty;
            string values = String.Empty;
            string computedColumns = String.Empty;
            string computedParameters = String.Empty;
            string computedComma = String.Empty;

            List<string> modifiedColumns = packet.ModifiedColumns;

            string sql = "BEGIN ";

            OracleParameter p = null;

            foreach (esColumnMetadata col in request.Columns)
            {
                if (col.IsAutoIncrement)
                {
                    p = CloneParameter(types[col.Name]);
                    p.Direction = ParameterDirection.Output;
                    p.Value = DBNull.Value;
                    cmd.Parameters.Add(p);

					// Oracle GENERATED BY DEFAULT AS IDENTITY — the value is assigned by Oracle
					// automatically in the INSERT. We retrieve it via RETURNING ... INTO
					// at the end of the INSERT. It is not included in INTO/VALUES.
					// The Output parameter is populated via the RETURNING clause added below.
                }
                else if (col.IsEntitySpacesConcurrency)
                {
                    p = CloneParameter(types[col.Name]);
                    p.Direction = ParameterDirection.Output;
                    cmd.Parameters.Add(p);

                    sql += p.ParameterName + " := 1; ";

                    into += comma;
                    into += Delimiters.ColumnOpen + col.Name + Delimiters.ColumnClose;
                    values += comma;
                    values += p.ParameterName;
                    comma = ", ";
                }
                else if (col.HasDefault && !IsColumnModified(packet, col))
                {
                    p = CloneParameter(types[col.Name]);
                    p.Direction = ParameterDirection.Output;
                    // ODP.NET requires DBNull.Value on Output parameters — null throws "Parameter cannot be null"
                    p.Value = DBNull.Value;
                    cmd.Parameters.Add(p);

                    computedColumns += computedComma + Delimiters.ColumnOpen + col.Name + Delimiters.ColumnClose;
                    computedParameters += computedComma + p.ParameterName;
                    computedComma = ", ";

                    if (col.CharacterMaxLength > 0)
                    {
                        p.Size = (int)col.CharacterMaxLength;
                    }
                }
            }

            esColumnMetadataCollection cols = request.Columns;

            #region Special Column Logic
            // Server-side special columns are filled by the DB (DEFAULT SYSTIMESTAMP
            // or trigger). Two things must change from the previous behavior:
            //
            //   1. Do NOT concatenate the ServerSideText value into the PL/SQL block.
            //      The value is the bareword "DateAdded", which Oracle rejects with
            //      PLS-00201 "identifier must be declared".
            //
            //   2. Do NOT include the column in the INSERT column list. The DB
            //      DEFAULT populates it; including it with a NULL placeholder produces
            //      ORA-01400 on the NOT NULL column.
            //
            // The value is retrieved via the RETURNING clause added below, and the
            // parameter is marked Output so the framework writes it back to
            // CurrentValues.
            if (cols.DateAdded != null && cols.DateAdded.IsServerSide)
            {
                p = CloneParameter(types[cols.DateAdded.ColumnName]);
                p.Direction = ParameterDirection.Output;
                cmd.Parameters.Add(p);
            }

            if (cols.DateModified != null && cols.DateModified.IsServerSide)
            {
                p = CloneParameter(types[cols.DateModified.ColumnName]);
                p.Direction = ParameterDirection.Output;
                cmd.Parameters.Add(p);
            }

            if (cols.AddedBy != null && cols.AddedBy.IsServerSide)
            {
                p = CloneParameter(types[cols.AddedBy.ColumnName]);
                p.Size = (int)cols.FindByColumnName(cols.AddedBy.ColumnName).CharacterMaxLength;
                p.Direction = ParameterDirection.Output;
                cmd.Parameters.Add(p);
            }

            if (cols.ModifiedBy != null && cols.ModifiedBy.IsServerSide)
            {
                p = CloneParameter(types[cols.ModifiedBy.ColumnName]);
                p.Size = (int)cols.FindByColumnName(cols.ModifiedBy.ColumnName).CharacterMaxLength;
                p.Direction = ParameterDirection.Output;
                cmd.Parameters.Add(p);
            }
            #endregion

            sql += "INSERT INTO " + CreateFullName(request) + " ";

            // Iterate request.Columns (canonical metadata) rather than the raw
            // ModifiedColumns list, so that property-name-keyed modifications
            // coming from ApplyPostSaveKeys resolve to the correct metadata.
            foreach (esColumnMetadata col in request.Columns)
            {
                if (col.IsAutoIncrement) continue;
                if (col.IsEntitySpacesConcurrency) continue;
                if (col.HasDefault && !IsColumnModified(packet, col)) continue;
                if (!IsColumnModified(packet, col)) continue;

                p = cmd.Parameters.Add(CloneParameter(types[col.Name]));

                object value = GetColumnValue(packet, col);
                p.Value = value != null ? value : DBNull.Value;

                into += comma;
                into += Delimiters.ColumnOpen + col.Name + Delimiters.ColumnClose;
                values += comma;
                values += p.ParameterName;
                comma = ", ";
            }

            // Collect RETURNING clause for GENERATED AS IDENTITY columns
            string returningCols = string.Empty;
            string returningParams = string.Empty;
            string returningComma = string.Empty;
            foreach (esColumnMetadata col in request.Columns)
            {
                if (col.IsAutoIncrement)
                {
                    OracleParameter rp = cmd.Parameters[types[col.Name].ParameterName];
                    returningCols   += returningComma + Delimiters.ColumnOpen + col.Name + Delimiters.ColumnClose;
                    returningParams += returningComma + rp.ParameterName;
                    returningComma = ", ";
                }
            }

            // Special columns also need to be pulled back through RETURNING so
            // the DB-assigned values reach the entity's CurrentValues.
            if (cols.DateAdded != null && cols.DateAdded.IsServerSide)
            {
                OracleParameter rp = cmd.Parameters[types[cols.DateAdded.ColumnName].ParameterName];
                returningCols += returningComma + Delimiters.ColumnOpen + cols.DateAdded.ColumnName + Delimiters.ColumnClose;
                returningParams += returningComma + rp.ParameterName;
                returningComma = ", ";
            }
            if (cols.DateModified != null && cols.DateModified.IsServerSide)
            {
                OracleParameter rp = cmd.Parameters[types[cols.DateModified.ColumnName].ParameterName];
                returningCols += returningComma + Delimiters.ColumnOpen + cols.DateModified.ColumnName + Delimiters.ColumnClose;
                returningParams += returningComma + rp.ParameterName;
                returningComma = ", ";
            }
            if (cols.AddedBy != null && cols.AddedBy.IsServerSide)
            {
                OracleParameter rp = cmd.Parameters[types[cols.AddedBy.ColumnName].ParameterName];
                returningCols += returningComma + Delimiters.ColumnOpen + cols.AddedBy.ColumnName + Delimiters.ColumnClose;
                returningParams += returningComma + rp.ParameterName;
                returningComma = ", ";
            }
            if (cols.ModifiedBy != null && cols.ModifiedBy.IsServerSide)
            {
                OracleParameter rp = cmd.Parameters[types[cols.ModifiedBy.ColumnName].ParameterName];
                returningCols += returningComma + Delimiters.ColumnOpen + cols.ModifiedBy.ColumnName + Delimiters.ColumnClose;
                returningParams += returningComma + rp.ParameterName;
                returningComma = ", ";
            }

            if (into.Length != 0)
            {
                sql += "(" + into + ") VALUES (" + values + ")";
                if (returningCols.Length > 0)
                    sql += " RETURNING " + returningCols + " INTO " + returningParams;
                sql += "; ";
            }
            else if (returningCols.Length > 0)
            {
                // INSERT con solo columnas auto-increment — Oracle las genera todas
                sql += "DEFAULT VALUES";
                sql += " RETURNING " + returningCols + " INTO " + returningParams;
                sql += "; ";
            }

            if (computedColumns.Length > 0)
            {
                string where = String.Empty;

                foreach (esColumnMetadata col in request.Columns)
                {
                    if (col.IsInPrimaryKey)
                    {
                        // We need the were clause if there are defaults to bring back
                        p = types[col.Name];

                        if (where.Length > 0) where += " AND ";
                        where += Delimiters.ColumnOpen + col.Name + Delimiters.ColumnClose + " = " + p.ParameterName;

                        if (!cmd.Parameters.Contains(p.ParameterName))
                        {
                            p = CloneParameter(p);
                            p.Direction = ParameterDirection.Output;
                            cmd.Parameters.Add(p);
                        }
                    }
                }

                sql += " SELECT " + computedColumns + " INTO " + computedParameters + " FROM " + CreateFullName(request) + " WHERE (" + where + ");";
            }

            sql += " END;";

            cmd.CommandText = sql;
            cmd.CommandType = CommandType.Text;
            return cmd;
        }

        static private void CreateInsertSQLSnippet(string colName, OracleParameter p, ref string into, ref string values, ref string comma)
        {
            into += comma;
            into += Delimiters.ColumnOpen + colName + Delimiters.ColumnClose;
            values += comma;
            values += p.ParameterName;
            comma = ", ";
        }

